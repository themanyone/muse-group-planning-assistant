#!/usr/bin/env python3
"""Generate the developer pack's machine-made half (B-160).

Two artifacts, both derived from the frozen contract so
they can never drift from the server they describe:

- ``sdk/python/gpa_sdk.py`` — a small Python client for the
  whole /api/v1 surface. Standard library only (urllib), so
  an outside script runs it with zero installs. One method
  per operation, named from the path; the public-page sugar
  (``public_events`` / ``public_page``) is part of the
  template, not generated, because the pack advertises it.
- ``sdk/typescript/index.d.ts`` — the generated TypeScript
  types (frontend_types.ts) promoted into the package
  unchanged: one source of truth, two doors.

Determinism is the contract (the B-149 discipline): sorted
paths, fixed method order, no timestamps — the test suite
regenerates both files and requires byte-identical output,
so a hand-edit to a generated file fails loudly.

Run:  uv run python scripts/generate_sdk.py
"""

from __future__ import annotations

import hashlib
import json
import keyword
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC_PATH = ROOT / "OPENAPI.json"
SDK_PATH = ROOT / "sdk" / "python" / "gpa_sdk.py"
TS_SOURCE = ROOT / "frontend_types.ts"
TS_PATH = ROOT / "sdk" / "typescript" / "index.d.ts"

METHOD_ORDER = ("get", "post", "put", "patch", "delete")

HEADER = '''"""Group Planning Assistant — Python SDK (GENERATED FILE).

Generated by scripts/generate_sdk.py from OPENAPI.json
(spec sha256 {spec_hash}). Do not edit by hand — regenerate.
Standard library only: this file runs anywhere Python 3.11+
runs, with nothing to install. The developer pack's front
door is DEVELOPER.md at the repository root.

    client = GpaClient("https://plans.example.org", api_key="gpa_...")
    events = client.public_events("riverbend-community-trust")
"""

from __future__ import annotations

import json as _json
import urllib.error as _urlerror
import urllib.parse as _urlparse
import urllib.request as _urlrequest

__all__ = ["GpaClient", "GpaError"]


class GpaError(Exception):
    """The server answered with an error status. Carries the
    HTTP status and the parsed problem body (RFC 9457)."""

    def __init__(self, status: int, body: object) -> None:
        super().__init__(f"GPA API error {{status}}: {{body}}")
        self.status = status
        self.body = body


def _q(value: object) -> str:
    """Quote one path segment."""
    return _urlparse.quote(str(value), safe="")


class GpaClient:
    """A thin, honest client: one method per API operation.

    ``api_key`` is a self-service key (see DEVELOPER.md);
    browser-session tokens work through the same header.
    Nothing is retried silently and nothing is cached — what
    the server said is what you get, or a GpaError.
    """

    def __init__(
        self, base_url: str, api_key: str | None = None, timeout: float = 30.0
    ) -> None:
        self.base_url = base_url.rstrip("/")
        self.api_key = api_key
        self.timeout = timeout

    # Keys travel in the X-API-Key header (session tokens use
    # Authorization: Bearer — a different door, kept apart so
    # a leaked key never looks like a session).

    def _request(self, method: str, path: str, *, query=None, body=None):
        url = self.base_url + path
        if query:
            clean = {k: v for k, v in query.items() if v is not None}
            if clean:
                url += "?" + _urlparse.urlencode(clean, doseq=True)
        data = None
        headers = {"Accept": "application/json"}
        if body is not None:
            data = _json.dumps(body).encode("utf-8")
            headers["Content-Type"] = "application/json"
        if self.api_key:
            headers["X-API-Key"] = self.api_key
        request = _urlrequest.Request(url, data=data, headers=headers, method=method)
        try:
            with _urlrequest.urlopen(request, timeout=self.timeout) as response:
                raw = response.read()
        except _urlerror.HTTPError as err:
            raw = err.read()
            try:
                parsed = _json.loads(raw) if raw else None
            except ValueError:
                parsed = raw.decode("utf-8", "replace")
            raise GpaError(err.code, parsed) from None
        if not raw:
            return None
        return _json.loads(raw)

    # -- The public surface, advertised by the pack --------

    def public_page(self, slug: str):
        """A public-listed group's public page (no key needed)."""
        return self.get_public_groups(slug)

    def public_events(self, slug: str):
        """A public-listed group's public events (no key needed)."""
        return self.list_public_groups_events(slug)

    # -- Generated operations (one per contract operation) --

'''

FOOTER = '''

# End of the generated operations. Regenerate with:
#   uv run python scripts/generate_sdk.py
'''


def _ident(segment: str) -> str:
    """A path segment as a Python identifier piece: hyphens
    and friends become underscores (magic-link → magic_link)."""
    cleaned = "".join(ch if ch.isalnum() else "_" for ch in segment)
    return cleaned.strip("_") or "root"


def _method_name(method: str, path: str, used: set[str]) -> str:
    """Derive a stable method name from method + path.

    GET ending at a {param} reads one thing (get_…); GET
    ending at a collection lists (list_…); other verbs use
    themselves (post_…, put_…, delete_…). Static segments
    join with underscores; collisions take a numeric suffix
    in sorted-path order, deterministically.
    """
    segments = [
        seg for seg in path.split("/") if seg and seg not in ("api", "v1")
    ]
    static = [
        _ident(seg) for seg in segments if not seg.startswith("{")
    ]
    ends_in_param = bool(segments) and segments[-1].startswith("{")
    if method == "get":
        verb = "get" if ends_in_param else "list"
    else:
        verb = method
    base = f"{verb}_{'_'.join(static)}" if static else verb
    name = base
    counter = 2
    while name in used:
        name = f"{base}_{counter}"
        counter += 1
    used.add(name)
    return name


def _render_operation(method: str, path: str, operation: dict, name: str) -> str:
    """Render one client method for one contract operation."""
    parameters = operation.get("parameters", [])
    path_params = [p["name"] for p in parameters if p.get("in") == "path"]
    query_params = [p["name"] for p in parameters if p.get("in") == "query"]
    has_body = "requestBody" in operation
    summary = (operation.get("summary") or "").strip().replace('"""', "'''")

    def py_name(wire: str) -> str:
        """A wire name as a Python argument: sanitised, and
        keyword-proof (the wire's ``from`` is our ``from_``)."""
        candidate = _ident(wire)
        if keyword.iskeyword(candidate) or not candidate.isidentifier():
            candidate += "_"
        return candidate

    args = ["self", *path_params]
    call_args: list[str] = []
    if query_params:
        args.append("*")
        args.extend(f"{py_name(q)}=None" for q in query_params)
        pairs = ", ".join(f'"{q}": {py_name(q)}' for q in query_params)
        call_args.append(f"query={{{pairs}}}")
    if has_body:
        if not query_params:
            args.append("*")
        args.append("body=None")
        call_args.append("body=body")

    url = path
    for param in path_params:
        url = url.replace("{" + param + "}", "{_q(" + param + ")}")
    signature = ", ".join(args)
    extra = (", " + ", ".join(call_args)) if call_args else ""
    return (
        f"    def {name}({signature}):\n"
        f'        """{method.upper()} {path} — {summary}"""\n'
        f'        return self._request("{method.upper()}", f"{url}"{extra})\n'
    )


def render_sdk(spec: dict, spec_hash: str) -> str:
    """The whole generated client, as text."""
    used: set[str] = set()
    methods: list[str] = []
    paths = spec["paths"]
    for path in sorted(paths):
        for method in METHOD_ORDER:
            operation = paths[path].get(method)
            if operation is None:
                continue
            name = _method_name(method, path, used)
            methods.append(_render_operation(method, path, operation, name))
    if not {"get_public_groups", "list_public_groups_events"} <= used:
        raise SystemExit(
            "A public operation vanished from the contract — "
            "the pack's advertised sugar would dangle. Fix the generator."
        )
    # .replace, not .format: the template is full of literal
    # braces (f-strings in the client body) that are not ours.
    return HEADER.replace("{spec_hash}", spec_hash) + "\n".join(methods) + FOOTER


def main() -> None:
    spec_bytes = SPEC_PATH.read_bytes()
    spec = json.loads(spec_bytes)
    spec_hash = hashlib.sha256(spec_bytes).hexdigest()[:16]
    SDK_PATH.parent.mkdir(parents=True, exist_ok=True)
    SDK_PATH.write_text(render_sdk(spec, spec_hash), encoding="utf-8")
    TS_PATH.parent.mkdir(parents=True, exist_ok=True)
    TS_PATH.write_bytes(TS_SOURCE.read_bytes())
    operations = sum(
        1
        for ops in spec["paths"].values()
        for method in ops
        if method in METHOD_ORDER
    )
    print(f"Wrote {SDK_PATH} ({operations} operations)")
    print(f"Wrote {TS_PATH} (promoted from frontend_types.ts)")


if __name__ == "__main__":
    main()
