#!/usr/bin/env python3
"""Generate TypeScript types from OPENAPI.json (roadmap B-006).

A small, honest generator: every component schema becomes an
exported interface/type in ``frontend_types.ts``. It covers the
JSON-Schema shapes this API actually uses (objects, scalars,
arrays, enums, $refs, nullable) and says so where a shape is beyond
it — the frontend crew gets typed models from day one without a
Node toolchain anywhere near the backend.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def ts_type(schema: dict) -> str:
    """Map one JSON-Schema fragment to a TypeScript type string."""
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    kind = schema.get("type")
    if kind == "string":
        return "string"
    if kind in ("integer", "number"):
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "array":
        return f"{ts_type(schema.get('items', {}))}[]"
    if kind == "object":
        return "Record<string, unknown>"
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    if "anyOf" in schema:
        parts = [ts_type(s) for s in schema["anyOf"]]
        if "null" in [s.get("type") for s in schema["anyOf"]]:
            return " | ".join(parts + ["null"])
        return " | ".join(parts)
    return "unknown"


def main() -> None:
    schema_path = ROOT / "OPENAPI.json"
    if not schema_path.exists():
        sys.exit("OPENAPI.json missing — run scripts/export_openapi.py first.")
    spec = json.loads(schema_path.read_text(encoding="utf-8"))
    schemas = spec.get("components", {}).get("schemas", {})
    lines = [
        "// Generated by scripts/generate_ts_types.py from OPENAPI.json.",
        "// Do not edit by hand — regenerate after exporting a new contract.",
        "",
    ]
    for name, schema in sorted(schemas.items()):
        if schema.get("type") == "object" or "properties" in schema:
            required = set(schema.get("required", []))
            lines.append(f"export interface {name} {{")
            for prop, prop_schema in sorted(schema.get("properties", {}).items()):
                optional = "" if prop in required else "?"
                nullable = " | null" if prop_schema.get("type") == "null" or any(
                    s.get("type") == "null" for s in prop_schema.get("anyOf", [])
                ) else ""
                lines.append(f"  {prop}{optional}: {ts_type(prop_schema)}{nullable};")
            lines.append("}")
        elif "enum" in schema:
            lines.append(f"export type {name} = {ts_type(schema)};")
        else:
            lines.append(f"export type {name} = {ts_type(schema)};")
        lines.append("")
    out = ROOT / "frontend_types.ts"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {out} ({len(schemas)} schemas)")


if __name__ == "__main__":
    main()
