#!/usr/bin/env python3
"""Generate RESULTS.md — the numbers page (roadmap B-149).

The submission quotes these numbers, so they are GENERATED,
never hand-typed: this script re-runs the three evaluation
harnesses (extraction B-046, vision B-073, pruning B-121)
against their shipped corpora and renders the tables. Running
it twice produces a byte-identical file (asserted by
tests/test_results_page.py) — the corpora and drivers are
deterministic fixtures, and no clock or random value enters
the page.

    uv run python scripts/make_results.py [output-path]
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from gpa.ai import evaluation, pruning_evaluation, vision_evaluation  # noqa: E402


def render() -> str:
    """Build the RESULTS.md text from fresh harness runs."""
    extraction = evaluation.evaluate()
    vision = vision_evaluation.run_vision_evaluation()
    pruning = pruning_evaluation.evaluate_pruning()

    lines = [
        "# Results — the numbers page",
        "",
        "Generated by `scripts/make_results.py` (roadmap B-149) from the",
        "shipped evaluation corpora. Never hand-edit the numbers: re-run",
        "the script. Every corpus below is deliberately imperfect, so a",
        "perfect score would be a warning sign, not a triumph.",
        "",
        "## Extraction (B-046)",
        "",
        "Corpus: `src/gpa/ai/eval_corpus.json` — golden chats and a",
        "newsletter with human-marked expected fields; dates are scored",
        "on the RESOLVED date. One place is genuinely ambiguous (precision",
        "0.50 by design) and one cost is never stated (recall 0.00).",
        "",
        "| Kind:field | Precision | Recall |",
        "|---|---|---|",
    ]
    for key in sorted(extraction):
        m = extraction[key]
        lines.append(f"| {key} | {m['precision']:.2f} | {m['recall']:.2f} |")

    lines += [
        "",
        "## Vision (B-073)",
        "",
        "Corpus: `src/gpa/ai/vision_eval_corpus.json` — four golden flyers",
        "(clean, handwriting, rotated, glare) read through the real",
        "pipeline with the fixture driver; each imperfect type misses",
        "exactly one field by design.",
        "",
        "| Flyer type | Score |",
        "|---|---|",
    ]
    # The vision report's shape: per-type scores under "by_type"
    # (falling back to the overall figure if the shape changes).
    for key in sorted(vision.get("by_type", {})):
        lines.append(f"| {key} | {vision['by_type'][key]:.4f} |")
    lines.append(f"| **overall** | **{vision['overall_accuracy']:.4f}** |")

    lines += [
        "",
        "## Context pruning (B-121)",
        "",
        "Corpus: `src/gpa/ai/pruning_eval_corpus.json` — golden questions",
        "with human-marked relevant chunks, judged by a recorded driver",
        "that is deliberately imperfect (one named miss, one over-keep).",
        "",
        "| Metric | Score |",
        "|---|---|",
    ]
    lines.append(f"| mean_precision | {pruning['mean_precision']:.2f} |")
    lines.append(f"| mean_recall | {pruning['mean_recall']:.2f} |")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "RESULTS.md"
    out.write_text(render(), encoding="utf-8")
    print(f"Wrote {out}")


if __name__ == "__main__":
    main()
